package gfx

import "sync/atomic"

// 开发模式开关。
//
// ## 为什么需要它
//
// gfx 有几类「写错了但不报错」的坑，最典型的是 JSX 子节点位置写了 `{sig}`
// 而不是 `{sig()}` —— 界面停在初始值，控制台一声不响。这类坑的共同点是
// **内核分得清对错，却一直在沉默**，因为沉默是「宽容」的默认实现：任何值都
// 能被 ToString 成文本，于是没有任何一层会觉得需要报错。
//
// 要在这些点上发警告，但**生产构建不该为一个用户没问的内部细节刷屏** ——
// 那是库对用户 stderr 的侵占，而且打包成 exe 的应用没有 stderr 可看，刷了
// 也是白刷。所以诊断只在 dev 模式发，生产模式行为逐字不变。
//
// ## 为什么不在包 init() 里读环境变量
//
// 见 CONTRIBUTING 纪律 5：包级 init() 不得做平台 IO。os.Getenv 虽然轻，但它
// 让「库的行为」依赖「进程环境」—— 库被链接进任何二进制（包括跑 test262 的
// 那个）都会静默改变行为，而调用方毫不知情。环境变量由 cmd/gox 读，再显式
// SetDevMode 传进来：库保持「被调用才动」的惰性，测试也能直接开关而不必改
// 进程环境。
//
// 用 atomic 而非普通 bool：gfx 主体是单线程 GUI（脚本/事件泵/VM 回调同线程
// 串行），但测试会并发断言警告环，这里不想引入「只有测试才需要加锁」的隐患。

var devMode atomic.Bool

// SetDevMode 开关开发模式。由 cmd/gox（读 GOX_DEV 环境变量）与测试调用。
func SetDevMode(on bool) { devMode.Store(on) }

// DevMode 报告当前是否处于开发模式。
//
// 只在**诊断出口**上判断，不影响任何渲染语义 —— 这是本开关的硬约束：
// dev 与生产跑出来的界面必须逐像素一致，否则「dev 下测过」就失去意义。
func DevMode() bool { return devMode.Load() }
