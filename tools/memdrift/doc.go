// Package memdrift 是 GUI 常驻进程的长时内存漂移测试（T3-3）。
//
// 为什么需要它：gox 的渲染层是无 GC 设计（帧缓冲 / 对象池手工复用），
// 泄漏在这种设计下不表现为崩溃，只表现为 RSS 单调上行。`scripts/rss-curve.sh`
// 回答的是"真进程挂 N 分钟 RSS 长什么样"，本包回答"同一件事能不能自动判定"——
// 它不进 PR（跑一次 1~3 分钟），而是让任何人用一条 `go test` 复现闸门。
//
// 一轮循环（cycle）刻意包含三件事，缺一件就测不到对应的泄漏面：
//   - 求值：新建 VM 并执行入口脚本（解析 / 编译 / 全局对象）；
//   - 组件挂载：脚本里的 render() 走真实 gfx.Mount（窗口工厂换成无窗口替身）；
//   - 渲染：调 __tick() 改信号 → 响应式 effect 标脏 → Layout + 脏区 Draw + 上屏。
//
// 判定口径（为什么这么定，见 docs/performance.md §11）：
//   - 每 K 轮强制一次 runtime.GC 后再采样：泄漏的定义是"GC 之后仍然留着的
//     对象"，不 GC 就只是在测"这一轮分配了多少"。
//   - 前 30% 的轮次只预热不判定：字体/字形缓存、对象池、Go 堆的首次增长都在
//     这里一次性发生，算进去会把"启动足迹"误判成"漂移"。
//   - 同时看两个信号：HeapAlloc（Go 堆活对象）与 VmRSS（进程实际占用）。
//     前者抓住典型的 Go 泄漏，后者抓住"堆没涨但内存没还给 OS"（arena 碎片、
//     手工池只拿不放）——无 GC 设计恰恰容易出现后者。
//
// 平台：Linux（VmRSS 读 /proc/self/status）。其他平台不编译本包。
