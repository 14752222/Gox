// Package perf 是 M9「并发与性能」的**可复现性能基准设施**。
//
// 本包只做"测量与判定依据", **不改 vm/ 与 gfx/ 的内核**。它回答两个出口
// 验收问题:
//
//  1. 解释器算力 —— 由 bench-compare.sh 的 gox / node / goja 三列数字回答
//     (本包不重复实现, 见 docs/performance.md 的基线表)。
//  2. UI 有没有 GC 毛刺 —— 由本包的帧率 / GC 停顿基准回答: 持续跑 N 帧
//     高频更新的真实 UI (走 gfx 的 Layout + 脏区 Draw + 上屏), 采集
//     帧间隔分布与 GC 停顿分布。
//
// # 口径 (为什么这么测)
//
//   - **帧间隔**: 以"一次上屏 (Surface.ShowRegions) 到下一次上屏"为区间。
//     它天然包含 JS 更新 + 响应式 effect + Layout + Draw + 任何 GC 停顿,
//     是"用户眼里的掉帧"最直接的代理量。用上屏时刻而非循环迭代时刻, 是为了
//     把"循环空转"排除在外。
//   - **GC 停顿**: 用 runtime/debug.ReadGCStats 读**本次测量窗口内新增**的
//     逐次停顿 (after.Pause 的前 NumGC 差 项)。不只看 PauseTotalNs 平均,
//     因为毛刺是分布尾部的现象, 平均值会把它抹平。
//   - **分配速率**: 另起一个采样 goroutine 每 2ms 读 TotalAlloc 差分,
//     避免在高频渲染循环里插入 ReadMemStats 污染帧间隔。峰值取任意 1s
//     滑动窗口内的最大分配字节数 / 秒。
//
// # 帧率 / GC 无毛刺的判定阈值 (建议值, 理由见 docs/performance.md)
//
//	p99 帧间隔 ≤ 16.7ms   (60fps 单帧预算, 尾部不越界才算稳)
//	max 单次 GC 停顿 ≤ 5ms (软件渲染 + 交互的可感知阈值)
//
// **为什么不用 max 帧间隔判**: 无独占的桌面上 max 会被 OS 调度抖动主导
// (实测同一负载连跑三次, max 在 2.3ms / 74ms / 141ms 之间摆动, 同期 GC
// 停顿稳定 <0.4ms)。所以 max 帧间隔与"超 16.7ms 帧占比"只作为报告字段,
// 判定只取稳健的 p99 与直接的 GC 停顿。
//
// 这些是**判定建议**, 不是硬闸门: 不同机器抖动不同, 硬卡会让 CI 误报。
// 基准只把实测值与 verdict 写进 JSON 并打印, 仅对"数量级劣化"硬失败。
